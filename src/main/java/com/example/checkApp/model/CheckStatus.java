package com.example.checkApp.model;

/**
 * Статус доступности чека — «все состояния мира» для мониторинга.
 *
 * <p>Всего два значения:</p>
 * <ul>
 *   <li>{@link #UP} — сервер ответил (любым HTTP-кодом): сайт доступен;</li>
 *   <li>{@link #DOWN} — соединение не удалось (таймаут, DNS, отказ): сайт лежит.</li>
 * </ul>
 *
 * <p>Хранится в БД <b>строкой</b> ({@code @Enumerated(EnumType.STRING)}): если завтра
 * появится третий статус (например, SLOW), существующие данные не «поеедут»,
 * как было бы при хранении порядкового номера (ordinal).</p>
 *
 * <p>Где используется: поле {@code lastStatus} у чека, поле {@code status}
 * у результата проверки, статус в ответах API и тексты телеграм-алертов.</p>
 */
public enum CheckStatus {
    UP,
    DOWN
}
