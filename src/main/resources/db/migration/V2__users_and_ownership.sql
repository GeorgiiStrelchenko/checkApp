-- Пользователи. Имя таблицы "users": "user" в PostgreSQL — зарезервированное слово.
-- password здесь хранит BCrypt-ХЭШ, а не пароль (см. UserService).
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,      -- BCrypt: "$2a$..."
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- UNIQUE: вторая линия защиты от дубликата логина
    -- (помимо проверки existsByUsername в коде — гонку ловит только БД)
    CONSTRAINT uq_users_username UNIQUE (username)
);

-- Владелец чека. Без DEFAULT и без NOT NULL: миграция применяется к УЖЕ
-- существующим чекам, у которых владельца ещё нет; приложение в этом же
-- Stage проставляет user_id при первых операциях.
ALTER TABLE checks ADD COLUMN user_id BIGINT REFERENCES users (id);

-- Список «моих чеков» (findByUserId) и фильтрация по владельцу.
CREATE INDEX idx_checks_user_id ON checks (user_id);

-- Каскады на удаление владельца не задаём (user_id может быть NULL,
-- а удалять пользователя целиком в UI-нет функции) — чистка вручную/каскадом
-- решается на уровне приложения (см. удаление чеков в CheckService).
