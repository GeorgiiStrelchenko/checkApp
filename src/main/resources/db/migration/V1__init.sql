-- Чеки: проверяемые сайты пользователей.
-- GENERATED BY DEFAULT AS IDENTITY = автоинкремент (в JPA — GenerationType.IDENTITY).
CREATE TABLE checks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    url VARCHAR(2048) NOT NULL,          -- длинные URL с query-строками
    check_interval_seconds INTEGER NOT NULL DEFAULT 60,  -- как часто пинговать, с
    enabled BOOLEAN NOT NULL DEFAULT TRUE,               -- выключенный = не проверяем
    last_status VARCHAR(16),              -- 'UP'/'DOWN', NULL = ещё не проверялся
    last_checked_at TIMESTAMP WITH TIME ZONE,            -- момент последнего пинга
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- История проверок: одна строка = один пинг.
-- ON DELETE CASCADE: удалили чек — его история удалиется вместе с ним
-- (иначе появились бы «осиротевшие» результаты).
CREATE TABLE check_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    check_id BIGINT NOT NULL REFERENCES checks (id) ON DELETE CASCADE,
    status VARCHAR(16) NOT NULL,         -- 'UP'/'DOWN' строкой, не числом:
                                         -- расширение enum не ломает данные
    http_code INTEGER,                   -- NULL = соединения не было
    response_time_ms BIGINT,             -- NULL = время не измерялось
    error_message VARCHAR(2048),         -- текст ошибки (обрезается в коде до 2048)
    checked_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Индексы под типичные запросы:
--  * выборка истории одного чека (findByCheckId...),
--  * «что было в окне статистики» (WHERE checked_at >= ...) и сортировка истории.
CREATE INDEX idx_check_results_check_id ON check_results (check_id);
CREATE INDEX idx_check_results_checked_at ON check_results (checked_at);
